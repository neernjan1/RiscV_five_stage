.section .text
.globl _start

_start:

################################################
# x1 = SPI Base Address (0x40003000)
################################################

lui     x1,0x40003

################################################
# CLKDIV = 4
################################################

addi    x2,x0,4
sw      x2,4(x1)
addi x0 , x0 ,0

################################################
# COMMAND = 0xA5
################################################

lui     x2,0xA5000
sw      x2,8(x1)
addi x0 , x0 ,0

################################################
# ADDRESS = 0x12340000
################################################

lui     x2,0x12340
sw      x2,12(x1)
addi x0 , x0 ,0

################################################
# SPILEN = 0x00080808
################################################

lui     x2,0x80
addi    x2,x2,0x708
addi    x2,x2,0x100
sw      x2,16(x1)
addi x0 , x0 ,0

################################################
# SPIDUM = 0
################################################

addi    x2,x0,0
sw      x2,20(x1)
addi x0 , x0 ,0

################################################
# START READ (RD=1, CS0=1)
################################################

addi    x2,x0,0x101
sw      x2,0(x1)
addi x0 , x0 ,0

################################################
# DEBUG:
# Read STATUS once immediately after START
################################################

lw      x6,0(x1)
addi x0 , x0 ,0

################################################
# Poll until IDLE bit becomes 1
################################################

poll:

lw      x3,0(x1)
addi x0 , x0 ,0

andi    x4,x3,1

beq     x4,x0,poll

################################################
# Save final STATUS
################################################

add     x7,x3,x0

################################################
# Read RXFIFO
################################################

lw      x5,32(x1)
addi x0 , x0 ,0

################################################
# Copy received data for debug
################################################

add     x8,x5,x0

################################################
# Endless loop
################################################

done:
beq x0,x0,done
