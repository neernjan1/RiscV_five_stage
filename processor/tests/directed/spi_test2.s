.section .text
.globl _start

_start:

####################################################
# SPI Base Address = 0x40003000
####################################################

lui     x1, 0x40003          # x1 = 0x40003000

####################################################
# Write CLKDIV = 4
####################################################

addi    x2, x0, 4
sw      x2, 4(x1)
addi    x0, x0, 0          # nop

####################################################
# Read CLKDIV
####################################################

lw      x3, 4(x1)
addi    x0, x0, 0          # nop

####################################################
# Write SPICMD = 0xA5000000
####################################################

lui     x2, 0xA5000          # x2 = 0xA5000000
sw      x2, 8(x1)
addi    x0, x0, 0          # nop

####################################################
# Read SPICMD
####################################################

lw      x4, 8(x1)
addi    x0, x0, 0          # nop

####################################################
# Read SPIADR
####################################################

lui     x1,0x40003

lui     x2,0x12345
addi    x2,x2,0x678

sw      x2,12(x1)
addi    x0, x0, 0          # nop

lw      x5,12(x1)
addi    x0, x0, 0          # nop

####################################################
# Read SPILEN
####################################################

lui     x1,0x40003
lui     x2,0x81808
addi    x2,x2,0x08

sw      x2,16(x1)
addi    x0, x0, 0          # nop

lw      x6,16(x1)
addi    x0, x0, 0          # nop

####################################################
# Read SPIDUM
####################################################

lui     x1,0x40003
addi    x2,x0,8

sw      x2,20(x1)
addi    x0, x0, 0          # nop

lw      x7,20(x1)
addi    x0, x0, 0          # nop

####################################################
# Read INTCFG
####################################################
lui     x1,0x40003
addi    x2,x0,3

sw      x2,36(x1)
addi    x0, x0, 0          # nop


lw      x8,36(x1)
addi    x0, x0, 0          # nop

####################################################
# Stop
####################################################

loop:
    j loop
