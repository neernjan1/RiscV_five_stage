.section .text
.globl _start

_start:

####################################################
# SPI Base Address = 0x40003000
####################################################

lui     x1, 0x40003          # x1 = 0x40003000

####################################################
# Write CLKDIV = 4
####################################################

addi    x2, x0, 4
sw      x2, 4(x1)
addi    x0, x0, 0          # nop

####################################################
# Read CLKDIV
####################################################

lw      x3, 4(x1)
addi    x0, x0, 0          # nop

####################################################
# Write SPICMD = 0xA5000000
####################################################

lui     x2, 0xA5000          # x2 = 0xA5000000
sw      x2, 8(x1)
addi    x0, x0, 0          # nop

####################################################
# Read SPICMD
####################################################

lw      x4, 8(x1)

addi    x0, x0, 0          # nop
addi    x0, x0, 0          # nop
addi    x0, x0, 0          # nop
addi    x0, x0, 0          # nop

####################################################
# Stop
####################################################

loop:
    j loop
