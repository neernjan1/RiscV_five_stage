.section .text
.globl _start

_start:

#########################################################
# ASCON BASE = 0x40000000
#########################################################

    lui x1,0x40000

#########################################################
# CONTROL = 0
#########################################################

    addi x2,x0,0
    sw x2,0(x1)
    addi x0,x0,0

#########################################################
# DATA LOW = 0x11111111
#########################################################

    lui x2,0x11111
    addi x2,x2,0x111
    sw x2,8(x1)
    addi x0,x0,0

#########################################################
# DATA HIGH = 0x22222222
#########################################################

    lui x2,0x22222
    addi x2,x2,0x222
    sw x2,12(x1)
    addi x0,x0,0

#########################################################
# KEY0 = 0xAAAAAAAA
#########################################################

    lui x2,0xAAAAB
    addi x2,x2,-1366
    sw x2,24(x1)
    addi x0,x0,0

#########################################################
# KEY1 = 0xBBBBBBBB
#########################################################

    lui x2,0xBBBBC
    addi x2,x2,-1093
    sw x2,28(x1)
    addi x0,x0,0

#########################################################
# KEY2 = 0xCCCCCCCC
#########################################################

    lui x2,0xCCCCD
    addi x2,x2,-820
    sw x2,32(x1)
    addi x0,x0,0

#########################################################
# KEY3 = 0xDDDDDDDD
#########################################################

    lui x2,0xDDDDE
    addi x2,x2,-547
    sw x2,36(x1)
    addi x0,x0,0

#########################################################
# NONCE0 = 0x12345678
#########################################################

    lui x2,0x12345
    addi x2,x2,0x678
    sw x2,40(x1)
    addi x0,x0,0

#########################################################
# NONCE1 = 0x89ABCDEF
#########################################################

    lui x2,0x89ABD
    addi x2,x2,-529
    sw x2,44(x1)
    addi x0,x0,0

#########################################################
# NONCE2 = 0x13579BDF
#########################################################

    lui x2,0x1357A
    addi x2,x2,-1057
    sw x2,48(x1)
    addi x0,x0,0

#########################################################
# NONCE3 = 0x2468ACE0
#########################################################

    lui x2,0x2468B
    addi x2,x2,-800
    sw x2,52(x1)
    addi x0,x0,0

#########################################################
# TAG INPUT0 = 0x11112222
#########################################################

    lui x2,0x11112
    addi x2,x2,0x222
    sw x2,72(x1)
    addi x0,x0,0

#########################################################
# TAG INPUT1 = 0x33334444
#########################################################

    lui x2,0x33334
    addi x2,x2,0x444
    sw x2,76(x1)
    addi x0,x0,0

#########################################################
# TAG INPUT2 = 0x55556666
#########################################################

    lui x2,0x55556
    addi x2,x2,0x666
    sw x2,80(x1)
    addi x0,x0,0

#########################################################
# TAG INPUT3 = 0x77778888
#########################################################

    lui x2,0x77779
    addi x2,x2,-1912
    sw x2,84(x1)
    addi x0,x0,0

#########################################################
# READ STATUS
#########################################################

    lw x10,4(x1)
    addi x0,x0,0

#########################################################
# READ OUTPUT DATA
#########################################################

    lw x11,16(x1)
    addi x0,x0,0

    lw x12,20(x1)
    addi x0,x0,0

#########################################################
# READ GENERATED TAG
#########################################################

    lw x13,56(x1)
    addi x0,x0,0

    lw x14,60(x1)
    addi x0,x0,0

    lw x15,64(x1)
    addi x0,x0,0

    lw x16,68(x1)
    addi x0,x0,0

done:

    jal x0,done
