.section .text
.globl _start

_start:

####################################################
# SPI Base Address = 0x40003000
####################################################

lui     x1,0x40003

####################################################
# CLKDIV = 4
# Offset = 0x004
####################################################

addi    x2,x0,4
sw      x2,4(x1)
addi    x0,x0,0

lw      x3,4(x1)
addi    x0, x0, 0          # nop

####################################################
# SPICMD = 0xA5000000
# Offset = 0x008
####################################################

lui     x2,0xA5000
sw      x2,8(x1)
addi    x0,x0,0

lw      x4,8(x1)
addi    x0, x0, 0          # nop

####################################################
# SPIADR = 0x12340000
# Offset = 0x00C
####################################################

lui     x2,0x12340
sw      x2,12(x1)
addi    x0,x0,0

lw      x5,12(x1)
addi    x0, x0, 0          # nop

####################################################
# SPILEN = 0x00080808
# Offset = 0x010
####################################################

lui     x2,0x00080
addi    x2,x2,0x708
addi    x2,x2,0x100
sw      x2,16(x1)
addi    x0,x0,0

lw      x6,16(x1)
addi    x0, x0, 0          # nop

####################################################
# SPIDUM = 0
# Offset = 0x014
####################################################

addi    x2,x0,0
sw      x2,20(x1)
addi    x0,x0,0

lw      x7,20(x1)
addi    x0, x0, 0          # nop

####################################################
# TXDATA = 0xB20000AA
# Offset = 0x018
####################################################

lui     x2,0xB2000
addi    x2,x2,0x0AA
sw      x2,24(x1)
addi    x0,x0,0




####################################################
# CSREG = 0x00000102
# Start SPI WRITE
# Offset = 0x000
####################################################

addi    x2,x0,0x102
sw      x2,0(x1)
addi    x0,x0,0

####################################################
# Stop
####################################################

loop:
    j loop
