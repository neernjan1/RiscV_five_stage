.section .text
.globl _start

_start:

#########################################################
# Normal Processor Instructions
#########################################################

    addi x10,x0,15
    addi x11,x0,25

    add  x12,x10,x11
    sub  x13,x11,x10
    xor  x14,x10,x11
    or   x15,x10,x11
    and  x16,x10,x11

    slli x17,x10,2
    srli x18,x17,1

#########################################################
# DMEM BASE = 0x80010000
#########################################################

    lui  x20,0x80010

#########################################################
# Store Values
#########################################################

    sw x12,0(x20)
    sw x13,4(x20)
    sw x14,8(x20)

#########################################################
# Read Back
#########################################################

    lw x21,0(x20)
    lw x22,4(x20)
    lw x23,8(x20)

#########################################################
# Branch Test
#########################################################

    beq x21,x12,branch_ok

    addi x24,x0,0

    jal x0,after_branch

branch_ok:

    lui  x24,0x1
    addi x24,x24,0x234

after_branch:

#########################################################
# SPI BASE = 0x40003000
#########################################################

    lui x1,0x40003

#########################################################
# CLKDIV = 4
#########################################################

    addi x2,x0,4
    sw   x2,4(x1)
    addi x0,x0,0

#########################################################
# CMD = 0xA5000000
#########################################################

    lui  x2,0xA5000
    sw   x2,8(x1)
    addi x0,x0,0

#########################################################
# ADDR = 0x12340000
#########################################################

    lui  x2,0x12340
    sw   x2,12(x1)
    addi x0,x0,0

#########################################################
# LEN = 0x00080808
#########################################################

    lui  x2,0x80
    addi x2,x2,0x708
    addi x2,x2,0x100
    sw   x2,16(x1)
    addi x0,x0,0

#########################################################
# DUMMY = 0
#########################################################

    addi x2,x0,0
    sw   x2,20(x1)
    addi x0,x0,0

#########################################################
# Some CPU Instructions
#########################################################

    addi x25,x21,100
    addi x26,x22,200
    add  x27,x25,x26

#########################################################
# START SPI READ
#########################################################

    addi x2,x0,0x101
    sw   x2,0(x1)
    addi x0,x0,0

#########################################################
# POLLING
#########################################################

poll:

    lw   x3,0(x1)
    addi x0,x0,0

    andi x4,x3,1

    beq  x4,x0,poll

#########################################################
# READ RX FIFO
#########################################################

    lw   x5,32(x1)
    addi x0,x0,0

#########################################################
# Continue Normal Processor Instructions
#########################################################

    add x28,x5,x12
    xor x29,x5,x13
    and x30,x5,x15
    or  x31,x5,x16

#########################################################
# Store SPI Result in DMEM
#########################################################

    sw x5,12(x20)

#########################################################
# Read Back
#########################################################

    lw x6,12(x20)

#########################################################
# Infinite Loop
#########################################################

done:

    jal x0,done
