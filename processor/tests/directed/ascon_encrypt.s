.section .text
.globl _start

_start:

#########################################################
# ASCON BASE ADDRESS = 0x40000000
#########################################################

    lui x1,0x40000

#########################################################
# KEY
#########################################################

# KEY0 = 0x0C0D0E0F

    lui x2,0x0C0D1
    addi x2,x2,-497
    sw x2,24(x1)
    addi x0,x0,0

# KEY1 = 0x08090A0B

    lui x2,0x08091
    addi x2,x2,-1525
    sw x2,28(x1)
    addi x0,x0,0

# KEY2 = 0x04050607

    lui x2,0x04050
    addi x2,x2,0x607
    sw x2,32(x1)
    addi x0,x0,0

# KEY3 = 0x00010203

    lui x2,0x00010
    addi x2,x2,0x203
    sw x2,36(x1)
    addi x0,x0,0

#########################################################
# NONCE
#########################################################

# NONCE0 = 0x0C0D0E0F

    lui x2,0x0C0D1
    addi x2,x2,-497
    sw x2,40(x1)
    addi x0,x0,0

# NONCE1 = 0x08090A0B

    lui x2,0x08091
    addi x2,x2,-1525
    sw x2,44(x1)
    addi x0,x0,0

# NONCE2 = 0x04050607

    lui x2,0x04050
    addi x2,x2,0x607
    sw x2,48(x1)
    addi x0,x0,0

# NONCE3 = 0x00010203

    lui x2,0x00010
    addi x2,x2,0x203
    sw x2,52(x1)
    addi x0,x0,0

#########################################################
# PLAINTEXT
#########################################################

# DATA LOW = 0x00001111

    lui x2,0x00001
    addi x2,x2,0x111
    sw x2,8(x1)
    addi x0,x0,0

# DATA HIGH = 0x11110000

    lui x2,0x11110
    sw x2,12(x1)
    addi x0,x0,0

#########################################################
# START ENCRYPTION
#########################################################

    addi x2,x0,1
    sw x2,0(x1)
    addi x0,x0,0

# Optional: clear control after start
    sw x0,0(x1)
    addi x0,x0,0

#########################################################
# WAIT FOR DONE
#########################################################

wait_done:

    lw x3,4(x1)
    addi x0,x0,0

    andi x4,x3,1          # done bit

    beq x4,x0,wait_done

#########################################################
# READ CIPHERTEXT
#########################################################

    lw x10,16(x1)
    addi x0,x0,0

    lw x11,20(x1)
    addi x0,x0,0

#########################################################
# READ AUTHENTICATION TAG
#########################################################

    lw x12,56(x1)
    addi x0,x0,0

    lw x13,60(x1)
    addi x0,x0,0

    lw x14,64(x1)
    addi x0,x0,0

    lw x15,68(x1)
    addi x0,x0,0

#########################################################
# END
#########################################################

done:
    jal x0,done




